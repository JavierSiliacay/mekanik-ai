                .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 20px; }
                .info-item { margin-bottom: 10px; }
                .info-label { font-size: 11px; color: #888; text-transform: uppercase; font-weight: bold; }
                .info-value { font-size: 14px; font-weight: 600; color: #222; }
                
                .neural-summary { background: #E8F5E9; border-radius: 8px; padding: 20px; border: 1px solid #C8E6C9; }
                .neural-summary p { margin: 0; font-style: italic; color: #2E7D32; font-size: 14px; }
                
