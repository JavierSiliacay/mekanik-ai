class PdfExportService(private val context: Context) {

    fun exportRepairManifesto(
        vehicle: Vehicle,
        scan: DiagnosticScan,
        records: List<DtcRecord>
    ) {
        val webView = WebView(context)
        val htmlContent = generateHtml(vehicle, scan, records)

        webView.webViewClient = object : WebViewClient() {
            override fun onPageFinished(view: WebView?, url: String?) {
                val printManager = context.getSystemService(Context.PRINT_SERVICE) as PrintManager
                val jobName = "Mekanik_AI_Report_${vehicle.licensePlate}_${scan.id}"
                val printAdapter = webView.createPrintDocumentAdapter(jobName)
                
                printManager.print(
                    jobName,
                    printAdapter,
                    PrintAttributes.Builder().build()
                )
            }
        }

        webView.loadDataWithBaseURL(null, htmlContent, "text/html", "utf-8", null)
    }

    fun shareRepairManifesto(
        vehicle: Vehicle,
        scan: DiagnosticScan,
        records: List<DtcRecord>
    ) {
        val webView = WebView(context)
        val htmlContent = generateHtml(vehicle, scan, records)

        webView.webViewClient = object : WebViewClient() {
            override fun onPageFinished(view: WebView?, url: String?) {
                val jobName = "Mekanik_AI_Share_${vehicle.licensePlate}_${scan.id}"
                val printAdapter = webView.createPrintDocumentAdapter(jobName)
                
                val attributes = PrintAttributes.Builder()
                    .setMediaSize(PrintAttributes.MediaSize.ISO_A4)
                    .setResolution(PrintAttributes.Resolution("pdf", "pdf", 600, 600))
                    .setMinMargins(PrintAttributes.Margins.NO_MARGINS)
                    .build()

                val file = File(context.cacheDir, "$jobName.pdf")
                val pfd = ParcelFileDescriptor.open(file, ParcelFileDescriptor.MODE_READ_WRITE or ParcelFileDescriptor.MODE_CREATE or ParcelFileDescriptor.MODE_TRUNCATE)

                printAdapter.onLayout(null, attributes, null, object : PrintDocumentAdapter.LayoutResultCallback() {
                    override fun onLayoutFinished(info: PrintDocumentInfo?, changed: Boolean) {
                        printAdapter.onWrite(arrayOf(PageRange.ALL_PAGES), pfd, null, object : PrintDocumentAdapter.WriteResultCallback() {
                            override fun onWriteFinished(pages: Array<out PageRange>?) {
                                pfd.close()
                                sharePdfFile(file, vehicle)
                            }
                        })
                    }
                }, null)
            }
        }

        webView.loadDataWithBaseURL(null, htmlContent, "text/html", "utf-8", null)
    }

    private fun sharePdfFile(file: File, vehicle: Vehicle) {
        val uri: Uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            file
        )

        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, "Mekanik AI Repair Manifesto: ${vehicle.year} ${vehicle.make} ${vehicle.model}")
            putExtra(Intent.EXTRA_TEXT, "Attached is the diagnostic Repair Manifesto for the vehicle ${vehicle.licensePlate} generated by Mekanik AI.")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }

        context.startActivity(Intent.createChooser(intent, "Share Repair Manifesto").apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        })
    }

