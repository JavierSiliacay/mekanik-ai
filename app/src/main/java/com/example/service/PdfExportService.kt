                    <h1>REPAIR MANIFESTO</h1>
                    <p>OFFICIAL VEHICLE HEALTH CERTIFICATE</p>
                </div>
            </div>

            <div class="section">
                <div class="section-title">Vehicle Identification</div>
                <div class="grid">
                    <div>
                        <div class="info-item">
                            <div class="info-label">Vehicle Name</div>
                            <div class="info-value">${vehicle.year} ${vehicle.make} ${vehicle.model}</div>
